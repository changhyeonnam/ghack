import { useCallback, useMemo, useRef, useState, type ReactNode } from 'react'
import { formatDateTime, formatFigure, humanize, modelDisplayName } from '../format'
import type { Case, Figure, Memo } from '../types'
import { EmptyState, RecommendationBadge, Skeleton, SkeletonText, SourcedSeal, recommendationLabel, REC_DESCRIPTION } from './Badges'
import { FigureChip, UnresolvedChip, tokenize } from './FigureChip'
import { Icon } from './Icons'
import { RefList } from './RefChip'
import { useViewer } from './viewerContext'

interface Props {
  memo: Memo | null
  kase: Case
  analyzeDone: boolean
  loading: boolean
}

export function MemoView({ memo, kase, analyzeDone, loading }: Props) {
  const viewer = useViewer()
  const [selectedId, setSelectedId] = useState<string | null>(null)
  const [trail, setTrail] = useState<string[]>([])
  const selectedRef = useRef<string | null>(null)
  selectedRef.current = selectedId

  const figuresById = useMemo(() => {
    const m = new Map<string, Figure>()
    for (const f of memo?.figures ?? []) m.set(f.id, f)
    return m
  }, [memo])

  // Footnote numbering in order of first appearance (used by the print stylesheet).
  const footnotes = useMemo(() => {
    const order: string[] = []
    const seen = new Set<string>()
    const visit = (text: string) => {
      for (const t of tokenize(text)) {
        if (t.kind === 'fig' && !seen.has(t.id) && figuresById.has(t.id)) {
          seen.add(t.id)
          order.push(t.id)
        }
      }
    }
    if (memo) {
      const d = memo.draft
      for (const s of d.sections) for (const p of s.paragraphs) visit(p)
      for (const s of d.strengths) visit(s)
      for (const s of d.concerns) visit(s)
      for (const s of d.conditions) visit(s)
      visit(d.rationale)
    }
    const idx = new Map<string, number>()
    order.forEach((id, i) => idx.set(id, i + 1))
    return { order, idx }
  }, [memo, figuresById])

  const selectFigure = useCallback(
    (fig: Figure, drill = false) => {
      const prev = selectedRef.current
      if (drill && prev && prev !== fig.id) setTrail((t) => [...t, prev])
      else if (!drill) setTrail([])
      setSelectedId(fig.id)
      // Open the first source ref; for computed figures without direct refs, fall back to the inputs' refs.
      let refs = fig.source_refs
      if (refs.length === 0 && fig.derived_from.length > 0) {
        refs = fig.derived_from.flatMap((id) => figuresById.get(id)?.source_refs ?? [])
      }
      if (refs.length > 0) viewer.openRefs(refs, fig.label)
    },
    [figuresById, viewer],
  )

  if (loading) return <MemoSkeleton />
  if (!memo) {
    return (
      <EmptyState
        icon="pen"
        title={analyzeDone ? 'Memo not available' : 'No memo yet'}
        hint={
          analyzeDone
            ? 'The Analyze stage finished but the memo could not be loaded. Try refreshing.'
            : 'Run the Analyze stage to generate the credit memo. Every number in it will link back to a document.'
        }
      />
    )
  }

  const d = memo.draft
  const selected = selectedId ? (figuresById.get(selectedId) ?? null) : null
  const unsourcedCount = memo.unsourced_numerals.length + memo.unresolved_figure_ids.length

  const inline = (text: string): ReactNode =>
    tokenize(text).map((part, i) => {
      if (part.kind === 'text') return <span key={i}>{part.value}</span>
      const fig = figuresById.get(part.id)
      if (!fig) return <UnresolvedChip key={i} id={part.id} />
      return <FigureChip key={i} figure={fig} selected={fig.id === selectedId} onSelect={(f) => selectFigure(f)} footnote={footnotes.idx.get(fig.id)} />
    })

  const closeEvidence = () => {
    setSelectedId(null)
    setTrail([])
  }

  return (
    <div className={`memo-layout${selected ? ' has-evidence' : ''}`}>
      <article className="memo" id="memo-print-root">
        <header className="memo-title">
          <div className="memo-kicker">
            <span>Credit memo</span>
            <span className="memo-kicker-sep" aria-hidden="true" />
            <span className="mono">v{memo.version}</span>
            {memo.baseline ? (
              <span className="badge badge-warn tip" data-tip="Generated by the single-prompt baseline, not the sourced pipeline">
                Baseline
              </span>
            ) : null}
          </div>
          <h2 className="memo-headline">{inline(d.headline)}</h2>
          <div className="memo-byline">
            <span className="memo-byline-item">
              <Icon name="bolt" size={12} /> Prepared by Analyst agent
            </span>
            <span className="memo-byline-sep" aria-hidden="true" />
            <span className="memo-byline-item tip" data-tip={memo.model}>
              {modelDisplayName(memo.model)}
            </span>
            <span className="memo-byline-sep" aria-hidden="true" />
            <span className="memo-byline-item mono">{memo.prompt_version}</span>
            <span className="memo-byline-sep" aria-hidden="true" />
            <span className="memo-byline-item">{formatDateTime(memo.created_at)}</span>
            <span className="memo-byline-sep" aria-hidden="true" />
            <SourcedSeal unsourced={unsourcedCount} />
          </div>
          <div className="memo-meta-print print-only">
            {kase.business_name} · {kase.country} · {kase.sector} · Case {kase.id}
          </div>
        </header>

        {unsourcedCount > 0 ? (
          <div className="callout callout-bad">
            <Icon name="alert" size={16} />
            <div>
              <strong>Numbers without evidence were found in this memo.</strong>
              <ul className="callout-list">
                {memo.unsourced_numerals.map((u, i) => (
                  <li key={i}>
                    <span className="mono">{u.text}</span> in <em>{u.section}</em>
                    {u.context ? <span className="muted"> — “{u.context}”</span> : null}
                  </li>
                ))}
                {memo.unresolved_figure_ids.map((id) => (
                  <li key={id}>
                    Unresolved figure id <span className="mono">{id}</span>
                  </li>
                ))}
              </ul>
            </div>
          </div>
        ) : null}

        <section className={`rec-banner rec-banner-${d.recommendation}`} aria-label="Recommendation">
          <div className="rec-banner-head">
            <span className="rec-banner-label">Analyst recommendation</span>
            <RecommendationBadge value={d.recommendation} large />
          </div>
          <p className="rec-banner-desc">{REC_DESCRIPTION[d.recommendation] ?? recommendationLabel(d.recommendation)}</p>
          {d.conditions.length > 0 ? (
            <ol className="rec-conditions">
              {d.conditions.map((c, i) => (
                <li key={i}>{inline(c)}</li>
              ))}
            </ol>
          ) : null}
        </section>

        {d.key_figure_ids.length > 0 ? (
          <section className="key-figures" aria-label="Key figures">
            {d.key_figure_ids.slice(0, 6).map((id) => {
              const fig = figuresById.get(id)
              if (!fig) return <UnresolvedChip key={id} id={id} />
              return <FigureChip key={id} figure={fig} size="card" selected={fig.id === selectedId} onSelect={(f) => selectFigure(f)} />
            })}
          </section>
        ) : null}

        {!selected ? (
          <p className="hint-row screen-only">
            <Icon name="anchor" size={12} /> Underlined values are sourced figures. Click one to open its evidence and highlight the document location.
          </p>
        ) : null}

        {d.sections.map((s, si) => (
          <section key={si} className="memo-section">
            <h3 className="memo-h">{s.heading}</h3>
            {s.paragraphs.map((p, pi) => (
              <p key={pi} className="memo-p">
                {inline(p)}
              </p>
            ))}
          </section>
        ))}

        <div className="memo-two-col">
          <section className="memo-section">
            <h3 className="memo-h">Strengths</h3>
            {d.strengths.length === 0 ? (
              <p className="muted small">None listed.</p>
            ) : (
              <ul className="memo-list memo-list-good">
                {d.strengths.map((s, i) => (
                  <li key={i}>
                    <Icon name="check-circle" size={14} />
                    <span>{inline(s)}</span>
                  </li>
                ))}
              </ul>
            )}
          </section>
          <section className="memo-section">
            <h3 className="memo-h">Concerns</h3>
            {d.concerns.length === 0 ? (
              <p className="muted small">None listed.</p>
            ) : (
              <ul className="memo-list memo-list-bad">
                {d.concerns.map((s, i) => (
                  <li key={i}>
                    <Icon name="alert-circle" size={14} />
                    <span>{inline(s)}</span>
                  </li>
                ))}
              </ul>
            )}
          </section>
        </div>

        <section className="memo-section">
          <h3 className="memo-h">Rationale</h3>
          <p className="memo-p">{inline(d.rationale)}</p>
        </section>

        <footer className="memo-footer">
          <span>
            {memo.figures.length} sourced figure{memo.figures.length === 1 ? '' : 's'} in catalog
          </span>
          <span className="memo-byline-sep" aria-hidden="true" />
          <span>
            Model <span className="mono">{memo.model}</span>
          </span>
          <span className="memo-byline-sep" aria-hidden="true" />
          <span>
            Prompt <span className="mono">{memo.prompt_version}</span>
          </span>
        </footer>

        {footnotes.order.length > 0 ? (
          <section className="memo-sources print-only" aria-label="Sources">
            <h3 className="memo-h">Sources</h3>
            <ol className="memo-sources-list">
              {footnotes.order.map((id) => {
                const f = figuresById.get(id)!
                return (
                  <li key={id}>
                    <span className="memo-src-label">{f.label}</span> <span className="mono">{formatFigure(f)}</span>
                    {f.source_refs.length > 0 ? (
                      <span className="memo-src-refs">
                        {' — '}
                        {f.source_refs.map((r) => `${viewer.docName(r.doc_id)}, p.${r.page}`).join('; ')}
                      </span>
                    ) : f.computation ? (
                      <span className="memo-src-refs mono"> — {f.computation}</span>
                    ) : null}
                  </li>
                )
              })}
            </ol>
          </section>
        ) : null}
      </article>

      {selected ? (
        <EvidencePanel
          figure={selected}
          figuresById={figuresById}
          trail={trail}
          onDrill={(f) => selectFigure(f, true)}
          onBack={() => {
            const prev = trail[trail.length - 1]
            setTrail((t) => t.slice(0, -1))
            const f = prev ? figuresById.get(prev) : null
            if (f) selectFigure(f)
            else setSelectedId(null)
          }}
          onClose={closeEvidence}
        />
      ) : null}
    </div>
  )
}

function EvidencePanel({
  figure,
  figuresById,
  trail,
  onDrill,
  onBack,
  onClose,
}: {
  figure: Figure
  figuresById: Map<string, Figure>
  trail: string[]
  onDrill: (f: Figure) => void
  onBack: () => void
  onClose: () => void
}) {
  return (
    <aside className="evidence screen-only" aria-label="Evidence">
      <div className="evidence-head">
        {trail.length > 0 ? (
          <button className="icon-btn" onClick={onBack} aria-label="Back to previous figure">
            <Icon name="chevron-left" />
          </button>
        ) : null}
        <span className="evidence-title">Evidence</span>
        <span className={`chip ${figure.origin === 'computed' ? 'chip-info' : figure.origin === 'application' ? '' : 'chip-success'}`}>
          {figure.origin === 'computed' ? 'Computed' : figure.origin === 'application' ? 'Application' : 'From document'}
        </span>
        <button className="icon-btn" onClick={onClose} aria-label="Close evidence">
          <Icon name="x" />
        </button>
      </div>
      <div className="evidence-body">
        <div className="evidence-value">
          <span className="evidence-label">{figure.label}</span>
          <span className="mono evidence-number">{formatFigure(figure)}</span>
          <span className="evidence-unit">
            {humanize(figure.unit)}
            {figure.currency ? ` · ${figure.currency}` : ''}
            <span className="mono evidence-id">{figure.id}</span>
          </span>
        </div>
        {figure.computation ? (
          <div className="evidence-row">
            <span className="evidence-k">Computation</span>
            <code className="evidence-code">{figure.computation}</code>
          </div>
        ) : null}
        <div className="evidence-row">
          <span className="evidence-k">
            Sources <span className="mono muted">{figure.source_refs.length}</span>
          </span>
          <RefList refs={figure.source_refs} label={figure.label} />
        </div>
        {figure.derived_from.length > 0 ? (
          <div className="evidence-row">
            <span className="evidence-k">
              Derived from <span className="mono muted">{figure.derived_from.length}</span>
            </span>
            <ul className="derived-tree">
              {figure.derived_from.map((id) => {
                const f = figuresById.get(id)
                if (!f) return <li key={id}><UnresolvedChip id={id} /></li>
                return (
                  <li key={id}>
                    <button type="button" className="derived-chip" onClick={() => onDrill(f)} title={f.id}>
                      <span className="derived-label truncate">{f.label}</span>
                      <span className="mono derived-value">{formatFigure(f, true)}</span>
                      <Icon name="chevron-right" size={12} />
                    </button>
                  </li>
                )
              })}
            </ul>
          </div>
        ) : null}
      </div>
    </aside>
  )
}

function MemoSkeleton() {
  return (
    <div className="memo-layout" aria-busy="true">
      <div className="memo">
        <Skeleton w={120} h={10} />
        <Skeleton w="70%" h={26} className="mt-2" />
        <Skeleton w="55%" h={12} className="mt-2" />
        <Skeleton w="100%" h={72} className="mt-4" radius={8} />
        <div className="skeleton-row mt-4">
          {Array.from({ length: 4 }, (_, i) => (
            <Skeleton key={i} h={76} radius={8} />
          ))}
        </div>
        <Skeleton w={160} h={14} className="mt-5" />
        <SkeletonText lines={4} className="mt-2" />
        <Skeleton w={200} h={14} className="mt-5" />
        <SkeletonText lines={3} className="mt-2" />
      </div>
    </div>
  )
}
